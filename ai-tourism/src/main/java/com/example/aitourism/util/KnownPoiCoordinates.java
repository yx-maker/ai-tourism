    /** 从名称中提取城市名（如「福州动物园」→「福州」），无则返回 null */
    private static String extractCity(String name) {
        if (name == null) return null;
        for (String c : CITY_NAMES) {
            if (name.contains(c)) return c;
        }
        return null;
    }

    /**
     * 城市一致性判定：候选 key 与城市线索冲突时返回 false。
     * key 不含任何城市名时视为通用景点名（如「动物园」），允许匹配。
     */
    private static boolean cityMatches(String cityHint, String key) {
        if (cityHint == null || cityHint.isBlank()) return true;
        String keyCity = extractCity(key);
        if (keyCity == null) return true;
        return cityHint.equals(keyCity);
    }
