-- =============================================================================
-- 预算系统「数据真实性分层」改造（2026-10-22）
--
-- 背景：原预算引擎的交通/住宿价格全部来自系数估算（模型价），
--      无法向用户证明价格真实。本次改造引入三级价格数据层：
--        1) 真实 API：火车票走聚合数据/极速数据（同步 12306），
--           命中后写入 t_train_price_cache 缓存（本表**只存真实 API 返回的票价**）
--        2) 快照表：酒店价格快照 t_hotel_price_snapshot（季度采集，标注来源与日期）
--        3) 系数估算：以上两级都拿不到时的兜底（系统标注「估算」）
--
-- 说明：t_hotel_price_snapshot 的首版种子数据整理自主流 OTA 平台公开报价
--      （经济=如家/汉庭/7天 档次，舒适=全季/桔子/维也纳 档次，品质=亚朵/希尔顿欢朋/高档民宿 档次），
--      采集日期 2026-10-22。**建议每季度用同样口径重新采集更新一次**，
--      更新时务必同步修改 collected_date 与 source —— 快照的价值就在于「可溯源的采集日期」。
-- =============================================================================

use aitourism;

-- -----------------------------------------------------------------------------
-- 酒店价格快照表（Snapshot 层）
-- -----------------------------------------------------------------------------
create table if not exists t_hotel_price_snapshot
(
    id              bigint auto_increment primary key,
    city_name       varchar(64)        not null comment '城市名（不带「市」后缀）',
    tier            varchar(16)        not null comment '档次: economy/comfort/premium',
    price_per_night decimal(10, 2)     not null comment '该档次参考房价（元/晚）',
    sample_hotel    varchar(128)       null comment '代表性酒店（用于展示快照来源）',
    source          varchar(128)       not null default 'OTA公开报价整理' comment '快照来源口径',
    collected_date  date               not null comment '采集日期（快照可溯源性关键字段）',
    created_time    datetime default CURRENT_TIMESTAMP not null comment '入库时间',
    constraint uk_city_tier unique (city_name, tier)
) comment '酒店价格快照表（预算系统 Snapshot 层，季度更新）';

-- -----------------------------------------------------------------------------
-- 火车票价缓存表（只缓存真实 API 返回的票价；无 API Key 时该表为空，自动降级估算）
-- -----------------------------------------------------------------------------
create table if not exists t_train_price_cache
(
    id           bigint auto_increment primary key,
    origin_city  varchar(64)        not null comment '出发城市',
    dest_city    varchar(64)        not null comment '到达城市',
    depart_date  varchar(10)        not null comment '出发日期 yyyy-MM-dd（12306 预售期 14 天内）',
    seat_type    varchar(16)        not null comment '席别: 二等座/一等座/硬卧/硬座/商务座/飞机经济舱 等',
    price        decimal(10, 2)     not null comment '单程真实票价（元）',
    provider     varchar(32)        not null comment '数据提供方: juhe/jisu',
    fetched_at   datetime default CURRENT_TIMESTAMP not null comment '抓取时间',
    constraint uk_train_route unique (origin_city, dest_city, depart_date, seat_type)
) comment '火车票价缓存表（仅存真实 API 返回，缓存 24 小时）';

