    /**
     * 按景点名 + 城市查找内置坐标（推荐入口）。
     *
     * <p><b>为什么必须传城市</b>：旧的纯包含匹配会把「福州动物园」匹配到内置表中的
     * 「杭州动物园」，导致福州行程的地图点位被画到杭州（120.15,30.25）。
     * 因此这里对「包含匹配」增加城市一致性校验：若景点名/入参能确定城市，
     * 则只接受同城市（或不含城市信息的通用名）的候选，跨城市一律拒绝。
     *
     * @param poiName 景点名（可含城市前缀）
     * @param city    景点所属城市（来自路线 JSON 的 city 字段），可为 null
     * @return [经度, 纬度]，未找到或城市冲突时返回 null
     */
    public static double[] getCoord(String poiName, String city) {
        if (poiName == null) return null;

        // 城市线索：优先用入参 city，其次从景点名中提取（如「福州动物园」→ 福州）
        String cityHint = (city != null && !city.isBlank()) ? city.trim() : extractCity(poiName);

        // 1) 精确匹配
        double[] coord = SPOTS.get(poiName);
        if (coord != null) return coord;

        // 2) 城市 + 名称 组合（如 福州 + 动物园 → 表里若有「福州动物园」则命中）
        if (cityHint != null && !poiName.startsWith(cityHint)) {
            coord = SPOTS.get(cityHint + poiName);
            if (coord != null) return coord;
        }

        // 3) 去后缀后再精确匹配（如「鼓山风景区」→「鼓山」）
        String normalized = poiName.replaceAll("(景区|风景区|公园|博物馆|遗址|文化区|步行街|老街|广场)$", "");
        coord = SPOTS.get(normalized);
        if (coord != null && cityMatches(cityHint, normalized) && !crossCityGeneric(cityHint, poiName, normalized)) {
            return coord;
        }

        // 4) 包含匹配：必须城市一致，杜绝跨城市张冠李戴
        for (Map.Entry<String, double[]> entry : SPOTS.entrySet()) {
            String key = entry.getKey();
            if (key.length() < 2) continue;
            if (!poiName.contains(key)) continue;
            if (!cityMatches(cityHint, key)) continue;
            // 「福州西湖」不应命中杭州的「西湖」：名称自带城市、而候选 key 完全没有城市信息时不采信
            if (crossCityGeneric(cityHint, poiName, key)) continue;
            return entry.getValue();
        }

        // 5) 仍未命中：退回城市中心坐标——宁可落在城市中心，也绝不画到别的城市
        return cityHint != null ? CITY_CENTERS.get(cityHint) : null;
    }

    /**
     * 跨城市通用名判定：景点名自带城市前缀（如「福州西湖」），而候选 key 完全不含城市信息
     * （如「西湖」）时，说明该 key 几乎必然属于别的城市（否则 key 也会带城市前缀），拒绝匹配。
     */
    private static boolean crossCityGeneric(String cityHint, String poiName, String key) {
        return cityHint != null && poiName.startsWith(cityHint) && extractCity(key) == null;
    }

